"""跨模块共享的业务常量。

与 `config.py` 的分工：`config.py` 承载**环境/部署配置**（可从环境变量覆盖），
本模块承载**业务口径**（属于产品定义，不应随部署环境变化）。

分数分段是全站唯一口径
----------------------
教务看板「成绩分布」、作业「分数段分布」、学情评语措辞三处必须共用 `SCORE_BANDS`，
**禁止在任何 service 内另立阈值表或另写 if 链**。

历史背景（`docs/REVIEW-2026-10-17-simplicity.md` S-01）：三处曾各有一套阈值
（教务 4 段 / 良好线 75，作业 5 段 / 良好线 80，评语裸写 90·75），导致同一分数
在不同页面落到不同等级——例如 78 分在教务看板显示「良好」、在作业分数段显示「中等」。
2026-10-18 经产品裁决统一为**五段、良好线 80**。

分段表示法（2026-10-25 修复 RBT-37 / 原 RBT-04）
-------------------------------------------------
旧表用 `min`/`max` **闭区间**描述每段，与写入侧允许的 `0-150` 及浮点分数直接冲突：

* `105` / `120` 分（150 制或加分作业）不在任何区间内 ⇒ 教务看板静默丢分，
  五段计数之和 < 样本数、百分比之和 < 100%；
* `89.5` 卡在「良好 80-89」与「优秀 90-100」的**整数缝**里 ⇒ 同样丢分；
* 而作业侧用的是 `segment_index()`（只比下界），同一分数在两处落到不同档。

现在只保留**下界** `min`，语义固定为半开区间 ``[min, 上一段 min)``（最后一段下界为 0，
``< 0`` 的脏数据由 `segment_index` 兜底归入末段）。于是：

* 首段天然覆盖 100 分以上（105 / 120 归「优秀」，**不单列加分档**——这是产品裁决：
  加分项仍属最高档，另立一段会让 100 制课程的饼图多出一个恒为 0 的空段）；
* `89.5` 归「良好」（`< 90`），不再落缝；
* `label` **仅供图表展示**，判定一律走 `segment_index()`，两者不得互相推导。
"""

# 成绩合法区间（写入侧校验口径）。`Score.score` 是 Float 且允许加分/150 制课程，
# 两侧必须同源，否则又会出现「能入库但统计看不见」的分数（RBT-37）。
SCORE_MIN = 0
SCORE_MAX = 150

# 五段，良好线 80。字段含义：
#   key   —— 稳定英文标识，供前端筛选与埋点引用（改动会影响前端状态，勿动）
#   label —— 区间文案（图表/表格展示；**不参与判定**，小数/越界分数以 min 为准）
#   name  —— 中文档位名
#   min   —— **下界（含）**；按分数降序排列，`segment_index` 依赖此顺序
SCORE_BANDS = (
    {"key": "excellent", "label": "90 分及以上", "name": "优秀", "min": 90},
    {"key": "good", "label": "80-89", "name": "良好", "min": 80},
    {"key": "medium", "label": "70-79", "name": "中等", "min": 70},
    {"key": "pass", "label": "60-69", "name": "及格", "min": 60},
    {"key": "fail", "label": "60 分以下", "name": "不及格", "min": 0},
)

# 关键分界线，由 SCORE_BANDS 派生——业务代码里不要再重写这些数字
EXCELLENT_LINE = SCORE_BANDS[0]["min"]  # 90
GOOD_LINE = SCORE_BANDS[1]["min"]  # 80
PASS_LINE = SCORE_BANDS[3]["min"]  # 60


def segment_index(score: int | float) -> int:
    """返回分数落在 ``SCORE_BANDS`` 中的下标（0=优秀 … 4=不及格）。

    这是**唯一的归段实现**。任何需要「某分属于第几段」的地方都应调用本函数，
    不要另写 if 链、也不要按 ``label`` 反推——否则又会多出一份阈值真源。

    越界兜底：``> SCORE_MAX`` 归入第 0 段，``< 0`` 归入最后一段。写入侧已有
    ``SCORE_MIN``/``SCORE_MAX`` 校验，这里不抛异常，避免统计接口因单条脏数据整体 500。
    """
    for i, band in enumerate(SCORE_BANDS):
        if score >= band["min"]:
            return i
    return len(SCORE_BANDS) - 1
